# R4 for OCM: the only cache whose series carry their own windows
# ---------------------------------------------------------------------------


def test_ocm_windows_each_series_by_its_own_max_age(tmp_path) -> None:
    """A day for the sparklines, a week for the burn series.

    The sparkline series feed a ~2h trend, so a point from yesterday can
    only stretch the window and distort the rate.  Burns are rare, so
    the burn series is kept for a week -- and a 2h window would turn one
    burn into an extrapolated ~84/week alarm.
    """
    path = _write(
        tmp_path / "ocm_cache.json",
        {
            "version": 2,
            "supply_history": [
                [FIXTURE_NOW - 25 * DAY / 24, 3000.0],  # 25h: outside the day
                [FIXTURE_NOW - 60, 4000.0],
            ],
            "burn_history": [
                [FIXTURE_NOW - 8 * DAY, 2.0],  # outside the week
                [FIXTURE_NOW - 6 * DAY, 11.0],  # inside it
                [FIXTURE_NOW - 60, 12.0],
            ],
        },
    )
    cache = OCMCache(max_history=120)

    cache.load_from_file(path, now=FIXTURE_NOW)

    assert cache.get_supply_history() == [(FIXTURE_NOW - 60, 4000.0)]
    assert cache.get_burn_history() == [
        (FIXTURE_NOW - 6 * DAY, 11.0),
        (FIXTURE_NOW - 60, 12.0),
    ]


