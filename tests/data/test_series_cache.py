def test_extra_payload_and_restore_extra_round_trip(tmp_path) -> None:
    class _WithExtra(_Probe):
        def __init__(self, max_history: int = 120) -> None:
            super().__init__(max_history)
            self.holder_count: int | None = None

        def extra_payload(self):
            return {"holder_count": self.holder_count}

        def restore_extra(self, payload, *, path, now, max_age=None):
            self.holder_count = payload.get("holder_count")
            return 3  # pretend three keyed points were unusable

    path = tmp_path / "probe.json"
    cache = _WithExtra()
    cache.holder_count = 17
    cache.save_to_file(str(path))
    assert json.loads(path.read_text())["holder_count"] == 17

    reloaded = _WithExtra()
    reloaded.load_from_file(str(path), now=1_700_000_000.0)
    assert reloaded.holder_count == 17


