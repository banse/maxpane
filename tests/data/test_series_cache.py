def test_record_drops_none_and_says_so() -> None:
    """CLAUDE.md: a failed read is ``None``, never ``0``.

    The series is persisted, so a sentinel written during an outage
    outlives it and reads afterwards as a real measurement.
    """
    cache = _Probe()

    assert cache.record("counts", 100.0, None) is False

    assert cache.get_series("counts") == []
    assert len(cache.counts) == 0


def test_record_keeps_a_real_zero() -> None:
    """The other half of the rule: ``0.0`` is a value, not a sentinel."""
    cache = _Probe()

    assert cache.record("counts", 100.0, 0.0) is True

    assert cache.get_series("counts") == [(100.0, 0.0)]


def test_record_coerces_to_float_and_respects_the_per_spec_maxlen() -> None:
    cache = _Probe(max_history=120)

    for i in range(5):
        cache.record("deltas", 100.0 + i, i)

    # maxlen=3 on the spec beats max_history=120.
    assert cache.get_series("deltas") == [(102.0, 2.0), (103.0, 3.0), (104.0, 4.0)]
    assert all(isinstance(v, float) for _, v in cache.get_series("deltas"))


def test_history_size_counts_the_first_declared_series() -> None:
    cache = _Probe()
    cache.record("deltas", 100.0, 1.0)
    assert cache.history_size == 0

    cache.record("counts", 100.0, 1.0)
    assert cache.history_size == 1


def test_mark_sets_latest_and_last_updated() -> None:
    cache = _Probe()
    assert cache.get_latest() is None
    assert cache.last_updated is None

    snap = _Snapshot(1_700_000_000.0)
    cache._mark(snap)

    assert cache.get_latest() is snap
    assert cache.last_updated == 1_700_000_000.0


