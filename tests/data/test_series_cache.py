def test_a_failed_write_leaves_no_tmp_file_behind(tmp_path, caplog) -> None:
    """``os.replace`` failing must not leave ``<path>.tmp`` to accumulate."""
    target = tmp_path / "probe.json"
    cache = _Probe()
    cache.record("counts", 1.0, 1.0)

    real_replace = os.replace

    def _boom(src, dst):
        raise OSError("disk full")

    os.replace = _boom
    try:
        with caplog.at_level("WARNING"):
            cache.save_to_file(str(target))  # must not raise
    finally:
        os.replace = real_replace

    assert not (tmp_path / "probe.json.tmp").exists()
    assert not target.exists()
    assert "Failed to save Probe cache" in caplog.text


def test_a_read_only_directory_is_not_fatal(tmp_path, caplog) -> None:
    """The other half of the same guard, without patching anything."""
    ro = tmp_path / "ro"
    ro.mkdir()
    target = ro / "probe.json"
    os.chmod(ro, stat.S_IRUSR | stat.S_IXUSR)
    try:
        with caplog.at_level("WARNING"):
            _Probe().save_to_file(str(target))  # must not raise
        assert list(ro.iterdir()) == []
    finally:
        os.chmod(ro, stat.S_IRWXU)

    assert "Failed to save Probe cache" in caplog.text


def test_save_then_load_round_trips_the_series(tmp_path) -> None:
    base = 1_700_000_000.0
