class _Versioned(_Probe):
    VERSION_KEY = "schema_version"
    VERSION = 2

    def __init__(self, max_history: int = 120) -> None:
        super().__init__(max_history)
        self.seen_versions: list[int] = []

    def before_load(self, payload, version) -> None:
        self.seen_versions.append(version)


@pytest.mark.parametrize(
    ("stored", "expected"),
    [(2, 2), ("banana", 1), (None, 1), (0, 1)],
    ids=["v2", "non-int", "null", "zero"],
)
def test_before_load_sees_the_version(tmp_path, stored, expected) -> None:
    path = _write(tmp_path / "probe.json", {"schema_version": stored, "counts": []})
    cache = _Versioned()

    cache.load_from_file(path, now=1_700_000_000.0)

    assert cache.seen_versions == [expected]


def test_a_cache_with_no_version_key_reads_version_1(tmp_path) -> None:
    """And writes no version key: adding one to a file that never had one
    makes an older build read its own file as a downgrade."""

    class _Unversioned(_Versioned):
        VERSION_KEY = None

    path = _write(tmp_path / "probe.json", {"schema_version": 2, "counts": []})
    cache = _Unversioned()

    cache.load_from_file(path, now=1_700_000_000.0)
    assert cache.seen_versions == [1]

    out = tmp_path / "out.json"
    cache.save_to_file(str(out))
    # The whole key set, not just the absence of one name: a mutation
    # that writes the version under the base's own default key would
    # sail past ``"schema_version" not in ...``.
    assert set(json.loads(out.read_text())) == {
        "saved_at",
        "max_history",
        "counts",
        "deltas",
    }


def test_a_version_key_is_written_when_the_subclass_names_one(tmp_path) -> None:
    out = tmp_path / "out.json"
    _Versioned().save_to_file(str(out))
    assert json.loads(out.read_text())["schema_version"] == 2


