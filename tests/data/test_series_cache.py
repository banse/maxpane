# The clock the fixtures were written against; every sample in them is at
# or before it, so no test here leans on the clock-skew tolerance.
FIXTURE_NOW = 1_758_000_000.0

DAY = 86_400.0


class _Snapshot:
    """The one attribute ``_mark`` reads off a snapshot."""

    def __init__(self, fetched_at: float) -> None:
        self.fetched_at = fetched_at


class _Probe(SeriesCache):
    """Two series that exercise the two per-spec knobs.

    ``deltas`` names its own ``maxlen`` and allows negatives (a delta
    series legitimately goes below zero); ``counts`` takes the cache-wide
    ``max_history`` and its own ``max_age`` window.
    """

    SERIES = (
        SeriesSpec("counts", max_age=600.0),
        SeriesSpec("deltas", maxlen=3, allow_negative=True),
    )
    NOUN = "Probe cache"


