"""``SeriesCache`` -- the one copy of the six caches' persistence code.

Five cache modules used to carry their own atomic write, their own
open/decode guard, their own per-point validation and their own
"Skipped ..." warning.  Branch 9 folded them into
``data/series_cache.SeriesCache``; these tests drive the base directly
through a probe subclass, and then drive the two real subclasses this
work package migrated against **fixtures written by the pre-branch
commit** (``tests/fixtures/cache/*_53a71d5.json``, generated by
``tests/scripts/make_cache_fixtures.py`` from a worktree of ``53a71d5``).
The fixture round-trips are the acceptance claim: a user's existing
``~/.maxpane/cattown_cache.json`` loads into the new class with exactly
the points the old class wrote.

The expected point lists below are transcribed from those files by hand.
Recomputing them from the same constants the fixture was built with
would prove only that arithmetic is deterministic.

Nothing here touches the network, the real clipboard or ``~/.maxpane``:
every path is ``tmp_path`` or a committed fixture, and every clock is
passed in.
"""

