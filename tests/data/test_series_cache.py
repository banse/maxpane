# #48: the three keyed caches merge on load, and all three say so
# ---------------------------------------------------------------------------


def _keyed_merge_case_bakery(cache: DataCache) -> None:
    cache._history["Kept Bakery"] = deque([(FIXTURE_NOW - 10, 1.0)], maxlen=120)


def _keyed_merge_case_base(cache: BaseTokenCache) -> None:
    cache.record_token(_base_token(BASE_TOKEN_3, 1.0), timestamp=FIXTURE_NOW - 10)


def _keyed_merge_case_frenpet(cache: FrenPetCache) -> None:
    cache._pet_histories[99] = deque([(FIXTURE_NOW - 10, 1.0)], maxlen=120)


@pytest.mark.parametrize(
    ("cls", "seed", "payload", "read_kept", "read_loaded"),
    [
        (
            DataCache,
            _keyed_merge_case_bakery,
            {"histories": {"Loaded Bakery": [[FIXTURE_NOW - 5, 2.0]]}},
            lambda c: c.get_cookie_history("Kept Bakery"),
            lambda c: c.get_cookie_history("Loaded Bakery"),
        ),
        (
            BaseTokenCache,
            _keyed_merge_case_base,
            {"histories": {BASE_TOKEN_1: [[FIXTURE_NOW - 5, 2.0]]}},
            lambda c: c.get_price_history(BASE_TOKEN_3),
            lambda c: c.get_price_history(BASE_TOKEN_1),
        ),
        (
            FrenPetCache,
            _keyed_merge_case_frenpet,
            {"schema_version": 2, "histories": {"7": [[FIXTURE_NOW - 5, 2.0]]}},
            lambda c: c.get_pet_score_history(99),
            lambda c: c.get_pet_score_history(7),
        ),
    ],
    ids=["bakery", "base", "frenpet"],
)
def test_a_keyed_load_merges_rather_than_replaces(
    tmp_path, cls, seed, payload, read_kept, read_loaded
) -> None:
    """Follow-up #48, decided: all three keep merging.

    A key already tracked in memory but absent from the file keeps its
    deque; a key in the file is written over whatever was there.  Every
    caller loads in ``__init__``, before its first ``update()``, so
    nothing live depends on the choice either way -- which is exactly
    why it is pinned here rather than left to drift into three different
    answers the next time one of these loaders is touched.  The keyed
    twin of R7, and the opposite decision, because R7 is about a series
    whose identity is fixed while these dicts' keys arrive and leave.
    """
    path = _write(tmp_path / "cache.json", payload)
    cache = cls(max_history=120)
    seed(cache)

    cache.load_from_file(path, now=FIXTURE_NOW)

    assert read_kept(cache) == [(FIXTURE_NOW - 10, 1.0)], "the load replaced"
    assert read_loaded(cache) == [(FIXTURE_NOW - 5, 2.0)]
    assert cache.history_size == 2
