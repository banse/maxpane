@pytest.mark.parametrize(
    ("name", "cls"),
    [("cattown", CatTownCache), ("dota", DOTACache)],
)
def test_the_persisted_shape_did_not_change(tmp_path, name, cls) -> None:
    """Load the pre-branch file, save it again, compare key for key.

    ``saved_at`` is the wall clock at write time and is the only key
    allowed to differ.  Notably, neither file gains a version key.
    """
    old = json.loads((FIXTURES / f"{name}_53a71d5.json").read_text())
    cache = cls(max_history=120)
    cache.load_from_file(str(FIXTURES / f"{name}_53a71d5.json"), now=FIXTURE_NOW)

    out = tmp_path / f"{name}.json"
    cache.save_to_file(str(out))
    new = json.loads(out.read_text())

    assert set(new) == set(old)
    assert "version" not in new and "schema_version" not in new
    for key in old:
        if key == "saved_at":
            continue
        assert new[key] == old[key], key


