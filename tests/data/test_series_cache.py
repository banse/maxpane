def test_record_token_honours_a_zero_timestamp() -> None:
    """R3. ``ts = timestamp or time.time()`` swallowed epoch ``0.0``.

    ``0.0`` is falsy, so the one caller who meant "stamp this at the
    epoch" silently got the wall clock instead -- the single value a
    test can use to tell an injected clock from a real one.  The
    in-memory point is what is asserted: ``coerce_points`` rejects a
    non-positive timestamp as corruption, so a ``0.0`` point does not
    survive a save/load round trip, and that is deliberate.
    """
    cache = BaseTokenCache(max_history=10)

    cache.record_token(_base_token(BASE_TOKEN_1, 4.5), timestamp=0.0)

    assert cache.get_price_history(BASE_TOKEN_1) == [(0.0, 4.5)]


def test_record_overview_point_skips_none_and_keeps_a_real_zero() -> None:
    """R1, on the method that is the repo's reference statement of it.

    A zero written while the upstream was down is persisted and then
    indistinguishable from a real reading: it crushes the ETH
    sparkline's scale and ``compute_volume_trend`` reads a zero previous
    volume as "Rising" on the next good cycle whatever the truth is.
    """
    cache = BaseTokenCache(max_history=10)

    cache.record_overview_point(
        timestamp=100.0, total_volume=None, eth_price=None, trade_count=None
    )
    cache.record_overview_point(
        timestamp=200.0, total_volume=0.0, eth_price=2500.0, trade_count=0
    )

    assert cache.get_volume_history() == [(200.0, 0.0)]
    assert cache.get_eth_price_history() == [(200.0, 2500.0)]
    assert cache.get_trade_count_history() == [(200.0, 0.0)]


