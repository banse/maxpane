def _write(path: Path, payload) -> str:
    path.write_text(json.dumps(payload))
    return str(path)


def test_load_validates_points_against_now_not_the_wall_clock(tmp_path) -> None:
    """``now=`` is the reference, or the same file loads differently by hour.

    The good point is 400 s *after* the injected ``now`` -- beyond the
    300 s skew tolerance, so it is corruption from that clock's point of
    view. Against the real wall clock (2026 and counting) it is deep in
    the past and would survive, so a loader that reached for
    ``time.time()`` here would keep it.
    """
    base = 1_700_000_000.0
    path = _write(
        tmp_path / "probe.json",
        {"counts": [[base - 60, 1.0], [base + 400, 2.0]]},
    )
    cache = _Probe()

    cache.load_from_file(path, now=base)

    assert cache.get_series("counts") == [(base - 60, 1.0)]


def test_a_spec_max_age_beats_the_calls_max_age(tmp_path) -> None:
    """``counts`` windows itself at 600 s; ``deltas`` takes the argument."""
    base = 1_700_000_000.0
    path = _write(
        tmp_path / "probe.json",
        {
            "counts": [[base - 900, 1.0], [base - 300, 2.0]],
            "deltas": [[base - 900, 3.0], [base - 300, 4.0]],
        },
    )
    cache = _Probe()

    # A generous call-level window: the spec's 600 s still drops the
    # 900-s-old count, while the un-specced deltas keep both points.
    cache.load_from_file(path, now=base, max_age=10 * DAY)

    assert cache.get_series("counts") == [(base - 300, 2.0)]
    assert cache.get_series("deltas") == [(base - 900, 3.0), (base - 300, 4.0)]


def test_allow_negative_is_per_spec(tmp_path) -> None:
    base = 1_700_000_000.0
