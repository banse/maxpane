    with caplog.at_level("WARNING"):
        cache.load_from_file(path, now=base)

    assert "overview_volume" in caplog.text
    assert "is not a list" in caplog.text
    assert "Base token cache" in caplog.text
    # The healthy sibling series is unaffected.
    assert cache.get_eth_price_history() == [(base - 10, 1.0)]
    assert cache.get_volume_history() == []
    # One line, not one per point.
    assert caplog.text.count("is not a list") == 1
