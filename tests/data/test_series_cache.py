def _dota_state(lanes: dict[str, DOTALane]) -> DOTAGameState:
    base = DOTABase(hp=1_000, maxHp=1_000)
    return DOTAGameState(
        tick=1,
        agents={},
        lanes=lanes,
        towers=[],
        bases={"human": base, "orc": base},
        heroes=[],
        winner=None,
    )


def test_a_missing_lane_records_nothing() -> None:
    """A frontline of 0 is a level lane, so an absent lane must not
    become one: it would draw a battle that never happened."""
    cache = DOTACache()
    lanes = {"top": DOTALane(human=5, orc=5, frontline=7)}

    cache.update(DOTASnapshot(fetched_at=1_700_000_000.0, game_state=_dota_state(lanes)))

    assert cache.get_top_history() == [(1_700_000_000.0, 7.0)]
    assert cache.get_mid_history() == []
    assert cache.get_bot_history() == []


